function csvEscape(value: unknown): string {
  const s = value === null || value === undefined ? '' : String(value);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

function toCsv(rows: Record<string, unknown>[], columns: string[]): string {
  const lines = [columns.join(',')];
  for (const row of rows) {
    lines.push(columns.map((c) => csvEscape(row[c])).join(','));
  }
  return lines.join('\n');
}

/** One row per logged set — the format anyone can open and analyse. */
export async function exportWorkoutsCsv(): Promise<string> {
  const [sessions, setLogs, exercises, notes] = await Promise.all([
    db.sessions.toArray(),
    db.setLogs.toArray(),
    db.exercises.toArray(),
    db.exerciseNotes.toArray(),
  ]);
  const noteFor = new Map(notes.map((n) => [`${n.sessionId}|${n.exerciseId}`, n.text]));

  const sessionById = new Map(sessions.map((s) => [s.id, s]));
  const exById = new Map(exercises.map((e) => [e.id, e]));

  const rows = setLogs
    .map((s) => {
      const session = sessionById.get(s.sessionId);
      if (!session) return null;
      return {
        date: session.date,
        workout: session.name,
        exercise: exById.get(s.exerciseId)?.name ?? s.exerciseId,
        target: exById.get(s.exerciseId)?.target ?? '',
        set: s.setIndex + 1,
        warmup: s.isWarmup ? 'yes' : 'no',
        weight_kg: s.weight ?? '',
        reps: s.reps ?? '',
        rpe: s.rpe ?? '',
        volume_kg: (s.weight ?? 0) * (s.reps ?? 0) || '',
        exercise_note: noteFor.get(`${s.sessionId}|${s.exerciseId}`) ?? '',
        feeling: session.feeling ?? '',
        session_notes: session.notes,
      };
    })
    .filter((r): r is NonNullable<typeof r> => r !== null)
    .sort(
      (a, b) =>
        a.date.localeCompare(b.date) ||
        a.workout.localeCompare(b.workout) ||
        a.exercise.localeCompare(b.exercise) ||
        a.set - b.set
    );

  return toCsv(rows, [
    'date', 'workout', 'exercise', 'target', 'set', 'warmup',
    'weight_kg', 'reps', 'rpe', 'volume_kg', 'exercise_note', 'feeling', 'session_notes',
  ]);
}

export async function exportCardioCsv(): Promise<string> {
  const rows = (await db.cardio.toArray())
    .sort((a, b) => a.date.localeCompare(b.date))
    .map((c) => ({
      date: c.date,
      type: c.type,
      title: c.title,
      distance_km: c.distanceKm ?? '',
      duration_min: c.durationSec ? Math.round(c.durationSec / 60) : '',
      pace_per_km: c.paceSecPerKm
        ? `${Math.floor(c.paceSecPerKm / 60)}:${String(Math.round(c.paceSecPerKm % 60)).padStart(2, '0')}`
        : '',
      avg_hr: c.avgHr ?? '',
      max_hr: c.maxHr ?? '',
      calories: c.calories ?? '',
      source: c.source,
      notes: c.notes,
    }));

  return toCsv(rows, [
    'date', 'type', 'title', 'distance_km', 'duration_min', 'pace_per_km',
    'avg_hr', 'max_hr', 'calories', 'source', 'notes',
  ]);
}

