import { db, type CardioSession, type ProgressPhoto, type RecoveryDay } from '@/db/schema';

/**
 * Requirement #10: the user must be able to walk away with everything, in a
 * format readable without this app.
 *
 * The JSON backup is the complete, restorable copy. The CSVs are the
 * human-readable view — openable in Excel or Sheets with no tooling.
 */

export const BACKUP_VERSION = 1;

interface BackupPhoto {
  id: string;
  date: string;
  pose: string;
  note: string;
  /** data: URL, so the backup is a single self-contained file. */
  dataUrl: string;
}

function blobToDataUrl(blob: Blob): Promise<string> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(String(reader.result));
    reader.onerror = () => reject(reader.error);
    reader.readAsDataURL(blob);
  });
}

async function dataUrlToBlob(dataUrl: string): Promise<Blob> {
  const res = await fetch(dataUrl);
  return res.blob();
}

export async function exportBackup(opts: { includePhotos: boolean; includeApiKey: boolean }) {
  const [
    programs, sessions, setLogs, weights, measurements,
    foodLogs, habits, habitLogs, reviews, settings, profile, exerciseNotes, cardio, recovery, photos,
  ] = await Promise.all([
    db.programs.toArray(),
    db.sessions.toArray(),
    db.setLogs.toArray(),
    db.weights.toArray(),
    db.measurements.toArray(),
    db.foodLogs.toArray(),
    db.habits.toArray(),
    db.habitLogs.toArray(),
    db.reviews.toArray(),
    db.settings.get('settings'),
    db.profile.get('profile'),
    db.exerciseNotes.toArray(),
    db.cardio.toArray(),
    db.recovery.toArray(),
    opts.includePhotos ? db.photos.toArray() : Promise.resolve([] as ProgressPhoto[]),
  ]);

  const backupPhotos: BackupPhoto[] = [];
  for (const p of photos) {
    backupPhotos.push({
      id: p.id,
      date: p.date,
      pose: p.pose,
      note: p.note,
      dataUrl: await blobToDataUrl(p.blob),
    });
  }

  // The API key is a credential, not training data — it is left out unless the
  // user explicitly asks for it.
  const safeSettings = settings
    ? { ...settings, anthropicApiKey: opts.includeApiKey ? settings.anthropicApiKey : '' }
    : null;

  return {
    app: 'fitness-coach',
    backupVersion: BACKUP_VERSION,
    exportedAt: new Date().toISOString(),
    // Reference data is regenerated by `npm run data:build`, so it is not
    // duplicated into every backup.
    data: {
      programs,
      sessions,
      setLogs,
      weights,
      measurements,
      foodLogs,
      habits,
      habitLogs,
      reviews,
      settings: safeSettings,
      // The athlete profile is the whole context behind the numbers — losing it
      // on a restore would strip the injuries and constraints out of every
      // future review.
      profile: profile ?? null,
      exerciseNotes,
      cardio,
      recovery,
      photos: backupPhotos,
    },
  };
}

export async function importBackup(payload: unknown, mode: 'merge' | 'replace') {
  const parsed = payload as Awaited<ReturnType<typeof exportBackup>>;
  if (!parsed || parsed.app !== 'fitness-coach' || !parsed.data) {
    throw new Error('This does not look like a Coach backup file.');
  }
  if (parsed.backupVersion > BACKUP_VERSION) {
    throw new Error('This backup was made by a newer version of the app.');
  }

  const d = parsed.data;

  await db.transaction(
    'rw',
    [db.programs, db.sessions, db.setLogs, db.weights, db.measurements,
     db.foodLogs, db.habits, db.habitLogs, db.reviews, db.settings, db.profile,
     db.exerciseNotes, db.cardio, db.recovery, db.photos],
    async () => {
      if (mode === 'replace') {
        await Promise.all([
          db.programs.clear(), db.sessions.clear(), db.setLogs.clear(),
          db.weights.clear(), db.measurements.clear(), db.foodLogs.clear(),
          db.habits.clear(), db.habitLogs.clear(), db.reviews.clear(), db.photos.clear(),
          db.exerciseNotes.clear(), db.cardio.clear(), db.recovery.clear(),
        ]);
      }

      await Promise.all([
        db.programs.bulkPut(d.programs ?? []),
        db.sessions.bulkPut(d.sessions ?? []),
        db.setLogs.bulkPut(d.setLogs ?? []),
        db.weights.bulkPut(d.weights ?? []),
        db.measurements.bulkPut(d.measurements ?? []),
        db.foodLogs.bulkPut(d.foodLogs ?? []),
        db.habits.bulkPut(d.habits ?? []),
        db.habitLogs.bulkPut(d.habitLogs ?? []),
        db.reviews.bulkPut(d.reviews ?? []),
        db.exerciseNotes.bulkPut(d.exerciseNotes ?? []),
      ]);

      // Both tables carry a unique key besides the id, so a row that arrived by
      // another route — a CSV import, a hand entry — would make a blind bulkPut
      // throw and abort the whole merge. Matching rows take over the existing id.
      for (const c of (d.cardio ?? []) as CardioSession[]) {
        const existing = await db.cardio.where('dedupeKey').equals(c.dedupeKey).first();
        await db.cardio.put(
          existing ? { ...c, id: existing.id, notes: c.notes || existing.notes } : c
        );
      }
      for (const r of ((d as { recovery?: RecoveryDay[] }).recovery ?? [])) {
        const existing = await db.recovery.where('date').equals(r.date).first();
        await db.recovery.put(
          existing ? { ...r, id: existing.id, notes: r.notes || existing.notes } : r
        );
      }

      for (const p of d.photos ?? []) {
        await db.photos.put({
          id: p.id,
          date: p.date,
          pose: p.pose as ProgressPhoto['pose'],
          note: p.note,
          blob: await dataUrlToBlob(p.dataUrl),
        });
      }

      if (d.settings) {
        const current = await db.settings.get('settings');
        await db.settings.put({
          ...d.settings,
          id: 'settings',
          // Never let an imported file overwrite a key already on this device
          // with an empty one.
          anthropicApiKey: d.settings.anthropicApiKey || current?.anthropicApiKey || '',
        });
      }

      if (d.profile) {
        await db.profile.put({ ...d.profile, id: 'profile' });
      }
    }
  );
}

