export async function exportBodyCsv(): Promise<string> {
  const [weights, measurements] = await Promise.all([
    db.weights.toArray(),
    db.measurements.toArray(),
  ]);

  const rows = [
    ...weights.map((w) => ({ date: w.date, metric: 'weight', value: w.kg, unit: 'kg', note: w.note })),
    ...measurements.map((m) => ({ date: m.date, metric: m.key, value: m.cm, unit: 'cm', note: '' })),
  ].sort((a, b) => a.date.localeCompare(b.date));

  return toCsv(rows, ['date', 'metric', 'value', 'unit', 'note']);
}

export async function exportNutritionCsv(): Promise<string> {
  const logs = await db.foodLogs.toArray();
  const rows = logs
    .map((l) => ({
      date: l.date,
      meal: l.meal,
      food: l.name,
      grams: l.grams,
      kcal: Math.round(l.kcal),
      protein_g: Math.round(l.protein * 10) / 10,
      carbs_g: Math.round(l.carbs * 10) / 10,
      fat_g: Math.round(l.fat * 10) / 10,
    }))
    .sort((a, b) => a.date.localeCompare(b.date));

  return toCsv(rows, ['date', 'meal', 'food', 'grams', 'kcal', 'protein_g', 'carbs_g', 'fat_g']);
}

/**
 * Loads a coach-authored program file. Ids are regenerated so importing the
 * same plan twice gives two independent programs rather than silently
 * overwriting the one already in progress.
 */
export async function importProgram(payload: unknown): Promise<string> {
  const wrapper = payload as { app?: string; kind?: string; program?: unknown };
  const raw = (wrapper?.app === 'fitness-coach' && wrapper.kind === 'program'
    ? wrapper.program
    : payload) as Partial<import('@/db/schema').Program> | undefined;

  if (!raw || typeof raw !== 'object' || !Array.isArray(raw.days) || !raw.name) {
    throw new Error('This file does not contain a program.');
  }

  const { db: database, uid: newId } = await import('@/db/schema');

  const exerciseIds = new Set((await database.exercises.toArray()).map((e) => e.id));
  const missing: string[] = [];

  const days = raw.days.map((day) => ({
    id: newId(),
    name: day.name ?? 'Day',
    dayOfWeek: day.dayOfWeek ?? null,
    items: (day.items ?? [])
      .filter((item) => {
        for (const alt of item.alternatives ?? []) {
          if (!exerciseIds.has(alt)) missing.push(alt);
        }
        if (exerciseIds.has(item.exerciseId)) return true;
        missing.push(item.exerciseId);
        return false;
      })
      .map((item) => ({
        id: newId(),
        exerciseId: item.exerciseId,
        group: item.group ?? null,
        targetSets: item.targetSets ?? 3,
        targetReps: item.targetReps ?? '8-10',
        targetWeight: item.targetWeight ?? null,
        restSec: item.restSec ?? 90,
        notes: item.notes ?? '',
        alternatives: item.alternatives ?? [],
      })),
  }));

  if (missing.length) {
    throw new Error(
      `Unknown exercise ids in this file: ${[...new Set(missing)].slice(0, 5).join(', ')}`
    );
  }

  const id = newId();
  await database.programs.add({
    id,
    name: raw.name,
    description: raw.description ?? '',
    createdAt: new Date().toISOString(),
    archived: false,
    active: false,
    days,
    startDate: raw.startDate ?? null,
    weeks: raw.weeks ?? null,
    rotation: raw.rotation ?? false,
  });

  return id;
}

/**
 * Adds coach-chosen alternatives to programs he already has, matched by
 * exercise id. A patch file rather than a new program, because re-importing
 * would start a fresh program and leave the A/B rotation and history behind.
 *
 * Only plan items with no alternatives are filled. A list he has already
 * edited is his, and a patch must not overwrite it.
 */
export async function importAlternatives(payload: unknown): Promise<{ items: number; programs: number }> {
  const map = (payload as { alternatives?: unknown })?.alternatives;
  if (!map || typeof map !== 'object') throw new Error('This file does not contain alternatives.');
  const byExercise = map as Record<string, string[]>;

  const { db: database } = await import('@/db/schema');
  const exerciseIds = new Set((await database.exercises.toArray()).map((e) => e.id));
  const unknown = Object.entries(byExercise)
    .flatMap(([id, alts]) => [id, ...alts])
    .filter((id) => !exerciseIds.has(id));
  if (unknown.length) {
    throw new Error(`Unknown exercise ids in this file: ${[...new Set(unknown)].slice(0, 5).join(', ')}`);
  }

  let items = 0;
  let programs = 0;
  const all = (await database.programs.toArray()).filter((p) => !p.archived);
  for (const program of all) {
    let touched = false;
    const days = program.days.map((day) => ({
      ...day,
      items: day.items.map((item) => {
        const alts = byExercise[item.exerciseId];
        if (!alts?.length || item.alternatives?.length) return item;
        touched = true;
        items++;
        return { ...item, alternatives: alts.filter((id) => id !== item.exerciseId) };
      }),
    }));
    if (touched) {
      programs++;
      await database.programs.put({ ...program, days });
    }
  }
  return { items, programs };
}

export function downloadFile(filename: string, content: string | Blob, type = 'text/plain') {
  const blob = typeof content === 'string' ? new Blob([content], { type }) : content;
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function stamp(): string {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}
